import * as React from 'react'
import { cn } from '@/lib/utils'

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: 'default' | 'draft-card' }
>(({ className, variant = 'default', ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      'rounded-xl bg-[#141924] border border-[#1E293B] text-[#E2E8F0] shadow-sm transition-all duration-200',
      'hover:border-[#8B00FF]/30 hover:shadow-[0_0_20px_rgba(139,0,255,0.08)]',
      variant === 'draft-card' && [
        'relative overflow-hidden',
        '[clip-path:polygon(0_0,calc(100%-12px)_0,100%_12px,100%_100%,12px_100%,0_calc(100%-12px))]',
      ],
      className
    )}
    {...props}
  />
))
Card.displayName = 'Card'

